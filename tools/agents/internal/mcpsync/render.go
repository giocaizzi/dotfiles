package mcpsync

import (
	"bytes"
	"encoding/json"
	"fmt"
	"slices"
	"strings"
)

// RenderCodex renders .codex/config.toml deterministically.
func RenderCodex(servers map[string]ServerEntry) []byte {
	var b strings.Builder
	b.WriteString("# Generated by " + CurrentMarker + "; edit .mcp.json and run chezmoi-agents mcp sync.\n")

	names := make([]string, 0, len(servers))
	for name := range servers {
		names = append(names, name)
	}
	slices.Sort(names)

	for _, name := range names {
		renderCodexServer(&b, name, servers[name])
	}

	return []byte(b.String())
}

func renderCodexServer(b *strings.Builder, name string, entry ServerEntry) {
	if entry.URL != "" {
		renderCodexHTTPServer(b, name, entry)
		return
	}
	if entry.Command != "" {
		renderCodexStdioServer(b, name, entry)
	}
}

func renderCodexHTTPServer(b *strings.Builder, name string, entry ServerEntry) {
	fmt.Fprintf(b, "\n[mcp_servers.%q]\nurl = %q\n", name, entry.URL)
	if len(entry.Headers) == 0 {
		return
	}
	fmt.Fprintf(b, "\n[mcp_servers.%q.http_headers]\n", name)
	hdrKeys := make([]string, 0, len(entry.Headers))
	for k := range entry.Headers {
		hdrKeys = append(hdrKeys, k)
	}
	slices.Sort(hdrKeys)
	for _, k := range hdrKeys {
		fmt.Fprintf(b, "%q = %q\n", k, entry.Headers[k])
	}
}

func renderCodexStdioServer(b *strings.Builder, name string, entry ServerEntry) {
	fmt.Fprintf(b, "\n[mcp_servers.%q]\ncommand = %q\n", name, entry.Command)
	if len(entry.Args) > 0 {
		quoted := make([]string, len(entry.Args))
		for i, a := range entry.Args {
			quoted[i] = fmt.Sprintf("%q", a)
		}
		fmt.Fprintf(b, "args = [%s]\n", strings.Join(quoted, ", "))
	}
	if len(entry.Env) > 0 {
		fmt.Fprintf(b, "\n[mcp_servers.%q.env]\n", name)
		envKeys := make([]string, 0, len(entry.Env))
		for k := range entry.Env {
			envKeys = append(envKeys, k)
		}
		slices.Sort(envKeys)
		for _, k := range envKeys {
			fmt.Fprintf(b, "%q = %q\n", k, entry.Env[k])
		}
	}
}

type piConfig struct {
	GeneratedBy string                 `json:"_generatedBy"`
	MCPServers  map[string]ServerEntry `json:"mcpServers"`
}

// RenderPi renders .pi/mcp.json with 2-space indentation and trailing newline.
func RenderPi(servers map[string]ServerEntry) ([]byte, error) {
	cfg := piConfig{
		GeneratedBy: CurrentMarker,
		MCPServers:  servers,
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(cfg); err != nil {
		return nil, fmt.Errorf("encode pi config: %w", err)
	}

	return buf.Bytes(), nil
}

// RenderAntigravity returns identical JSON content as .pi/mcp.json.
func RenderAntigravity(piJSON []byte) []byte {
	out := make([]byte, len(piJSON))
	copy(out, piJSON)
	return out
}
